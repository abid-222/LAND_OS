"""
Base classes, Context, and Evidence schemas for LandOS Risk & Conflict Engine.
Enforces Global Rules:
- Output only 'indicators that need verification'.
- Never output or store: 'safe', 'unsafe', 'fraud', 'valid ownership', 'invalid ownership', or a single overall safety score.
- Bangla alert wording: 'সম্ভাব্য অসঙ্গতি, যাচাই প্রয়োজন'.
- Every alert has reason + evidence (at least 1 item). No evidence = no alert.
"""

import hashlib
import json
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

import pydantic


class AlertEvidence(pydantic.BaseModel):
    """
    Evidence item for an alert.
    Schema: {source_type, source_id, field, value, document_ref}.
    """

    source_type: str  # "deed" | "mutation" | "land_record" | "document" | "survey"
    source_id: str
    field: str
    value: Any
    document_ref: Optional[str] = None


class RuleAlert(pydantic.BaseModel):
    """
    Alert generated by a risk rule.
    Guarantees title_bn is 'সম্ভাব্য অসঙ্গতি, যাচাই প্রয়োজন' and evidence is non-empty.
    """

    rule_id: str
    severity: str  # "info" | "warn" | "high"
    title_bn: str = "সম্ভাব্য অসঙ্গতি, যাচাই প্রয়োজন"
    reason_bn: str
    evidence: List[AlertEvidence]
    rule_version: str = "v1.0"

    @pydantic.field_validator("evidence")
    @classmethod
    def validate_evidence(cls, v: List[AlertEvidence]) -> List[AlertEvidence]:
        if not v or len(v) == 0:
            raise ValueError(
                "Every alert must contain at least 1 evidence item. No evidence = no alert."
            )
        return v

    def evidence_hash(self) -> str:
        """Computes deterministic hash of rule_id and evidence for idempotent deduplication."""
        serialized = json.dumps(
            [e.model_dump() for e in self.evidence],
            sort_keys=True,
            default=str,
        )
        return hashlib.sha256(f"{self.rule_id}:{serialized}".encode("utf-8")).hexdigest()


@dataclass
class ParcelContext:
    """
    Aggregated context of a parcel for running conflict rules.
    Contains parcel attributes, associated baseline record, deeds, mutations, and linked document fields.
    """

    parcel_id: str
    mouza_id: str
    mouza_name: str
    main_no: int
    sub_no: Optional[int]
    area_decimal: float
    record: Optional[Dict[str, Any]] = None
    deeds: List[Dict[str, Any]] = field(default_factory=list)
    mutations: List[Dict[str, Any]] = field(default_factory=list)
    documents: List[Dict[str, Any]] = field(default_factory=list)
    region_code: Optional[str] = None
    all_registry_deeds: List[Dict[str, Any]] = field(
        default_factory=list
    )  # For global duplicate check (R2)


class BaseRiskRule(ABC):
    """Abstract base class for LandOS risk and conflict rules."""

    id: str
    description: str

    @abstractmethod
    def run(self, ctx: ParcelContext) -> List[RuleAlert]:
        """Evaluates parcel context and returns list of RuleAlert objects."""
        pass
